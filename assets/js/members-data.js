document.addEventListener('DOMContentLoaded', () => {
  const tbody = document.getElementById('members-tbody');
  const btn = document.getElementById('members-view-more');
  if (!tbody || !btn) return;

  const pageSize = 20;
  let shown = 0;

  function renderNext() {
    const next = MEMBER_SHAREHOLDERS.slice(shown, shown + pageSize);
    const fragment = document.createDocumentFragment();
    next.forEach((member, i) => {
      const [name, village, shares] = member;
      const tr = document.createElement('tr');
      const cells = [String(shown + i + 1), name, village, String(shares)];
      cells.forEach((text, idx) => {
        const td = document.createElement('td');
        if (idx === 0 || idx === 3) td.className = 'num';
        td.textContent = text;
        tr.appendChild(td);
      });
      fragment.appendChild(tr);
    });
    tbody.appendChild(fragment);
    shown += next.length;

    if (shown >= MEMBER_SHAREHOLDERS.length) {
      btn.remove();
    } else {
      btn.textContent = `View more (${MEMBER_SHAREHOLDERS.length - shown} remaining)`;
    }
  }

  btn.addEventListener('click', renderNext);
  renderNext();
});
